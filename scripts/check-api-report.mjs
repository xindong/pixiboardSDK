import { readFile } from "node:fs/promises";
import { join, resolve } from "node:path";

const root = resolve(new URL("..", import.meta.url).pathname);
const reports = [
  ["pixiboardjs", join(root, "packages/pixiboardjs/etc/pixiboardjs.api.md")],
  ["@pixi-board/core", join(root, "packages/core/etc/pixi-board-core.api.md")],
  ["@pixi-board/plugin-sdk", join(root, "packages/plugin-sdk/etc/pixi-board-plugin-sdk.api.md")],
];
const blockers = [];

for (const [name, report] of reports) {
  try {
    const text = await readFile(report, "utf8");
    if (!text.includes("## API Report File")) blockers.push(`${name}: unexpected API report header`);
    if (text.includes("Do not edit this file by hand. Generate it") || text.includes("Generated from `dist")) blockers.push(`${name}: API report is an ungenerated template`);
    if (/node_modules|@pixi-board\/(adapter-browser|capabilities|renderer-pixi|plugin-api-v3)/.test(text)) blockers.push(`${name}: report references a private workspace package`);
  } catch (error) {
    if (error.code === "ENOENT") blockers.push(`${name}: missing generated API report`);
    else throw error;
  }
}

if (blockers.length) {
  console.error("API report blocked:");
  for (const blocker of blockers) console.error(`- ${blocker}`);
  process.exitCode = 1;
} else {
  console.log("API report baselines are present; release:check runs API Extractor production diff next.");
}
