import { readFile } from "node:fs/promises";
import { execFile } from "node:child_process";
import { promisify } from "node:util";
import { join, resolve } from "node:path";

const root = resolve(new URL("..", import.meta.url).pathname);
const run = promisify(execFile);
// Every published entry point needs its own report: API Extractor only walks
// the one `mainEntryPointFilePath` it is given, so a package with subpath
// exports would otherwise ship an unguarded public surface (`pixiboardjs/browser`
// carries the DOM overlay and persistence helpers, which live nowhere in the
// root entry's report).
// pixiboardjs is the only public package (ADR 0016); core, capabilities,
// agent-tools and plugin are its subpaths.
const entries = ["browser", "node", "types", "core", "capabilities", "agent-tools", "agent-tools-schemas", "plugin"];
const reports = [
  ["pixiboardjs", join(root, "packages/pixiboardjs/etc/pixiboardjs.api.md")],
  ...entries.map((entry) => [`pixiboardjs/${entry.replace("agent-tools-schemas", "agent-tools/schemas")}`, join(root, `packages/pixiboardjs/etc/pixiboardjs-${entry}.api.md`)]),
];
const extractorRuns = [
  ["pixiboardjs", []],
  ...entries.map((entry) => ["pixiboardjs", ["--config", `api-extractor.${entry}.json`]]),
];
const blockers = [];

for (const [name, report] of reports) {
  try {
    const text = await readFile(report, "utf8");
    if (!text.includes("## API Report File")) blockers.push(`${name}: unexpected API report header`);
    if (text.includes("Do not edit this file by hand. Generate it") || text.includes("Generated from `dist")) blockers.push(`${name}: API report is an ungenerated template`);
    if (/node_modules|from ['"]@pixi-board\//.test(text)) blockers.push(`${name}: report references a private workspace package`);
  } catch (error) {
    if (error.code === "ENOENT") blockers.push(`${name}: missing generated API report`);
    else throw error;
  }
}

if (blockers.length) {
  console.error("API report blocked:");
  for (const blocker of blockers) console.error(`- ${blocker}`);
  process.exitCode = 1;
} else {
  try {
    for (const [packageName, extraArgs] of extractorRuns) {
      await run("pnpm", ["--filter", packageName, "exec", "api-extractor", "run", "--verbose", ...extraArgs], { cwd: root });
    }
    console.log("API report compare passed: API Extractor production mode matches committed reports.");
  } catch (error) {
    console.error("API report compare blocked: API Extractor found a declaration/report difference or could not run.");
    if (error.stderr) console.error(error.stderr.trim());
    process.exitCode = 1;
  }
}
